using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

sealed partial class Model
{
    static string AttributeName(AttributeSyntax attribute) => attribute.Name.ToString().Split('.').Last().Replace("Attribute", "", StringComparison.Ordinal);
    static AttributeSyntax[] TypeAttributes(INamedTypeSymbol type) => type.DeclaringSyntaxReferences.Select(r => r.GetSyntax()).OfType<TypeDeclarationSyntax>()
        .SelectMany(d => d.AttributeLists.SelectMany(a => a.Attributes)).ToArray();
    static AttributeSyntax[] MethodAttributes(MethodDeclarationSyntax method) => method.AttributeLists.SelectMany(a => a.Attributes).ToArray();

    public DispatcherOutput GenerateStaticDispatcher(string pin, string profile)
    {
        var edits = new List<SourceEdit>();
        var rows = new List<StaticCallbackRow>();
        var rejected = new List<object>();
        var b = new StringBuilder("// <auto-generated />\n// Direct EHR static callback catalog: " + pin + "; " + profile + ". Native binding is a separate required integration.\n#nullable enable\nnamespace EHR;\ninternal static class EHRStaticPatchCatalog\n{\n    internal static readonly EHRStaticPatchDescriptor[] Descriptors = new EHRStaticPatchDescriptor[]\n    {\n");
        int index = 0;
        foreach (INamedTypeSymbol type in Types)
        {
            AttributeSyntax[] classAttrs = TypeAttributes(type);
            bool assemblyScan = classAttrs.Any(a => AttributeName(a) == "HarmonyPatch");
            var methods = type.GetMembers().OfType<IMethodSymbol>().SelectMany(m => m.DeclaringSyntaxReferences.Select(r => r.GetSyntax()).OfType<MethodDeclarationSyntax>()).ToArray();
            MethodDeclarationSyntax? prepare = methods.FirstOrDefault(m => m.Identifier.ValueText == "Prepare" || MethodAttributes(m).Any(a => AttributeName(a) == "HarmonyPrepare"));
            string? prepareBridge = null;
            var callbackMethods = methods.Where(m =>
            {
                AttributeSyntax[] attrs = MethodAttributes(m);
                bool hasScope = assemblyScan || attrs.Any(a => AttributeName(a) == "HarmonyPatch");
                return attrs.Any(a => AttributeName(a) is "HarmonyPrefix" or "HarmonyPostfix" or "HarmonyFinalizer")
                    || hasScope && m.Identifier.ValueText is "Prefix" or "Postfix" or "Finalizer";
            }).ToArray();
            if (callbackMethods.Length == 0) continue;
            if (declarations[type] is not ClassDeclarationSyntax classDecl || type.Arity != 0 || Parents(type).Any(p => p.Arity != 0))
            { rejected.Add(new { type = MetadataName(type), reason = "unsupported_patch_container_kind_or_generic_arity" }); continue; }
            MakeAccessible(type);
            if (prepare != null)
            {
                if (!prepare.Modifiers.Any(SyntaxKind.StaticKeyword) || prepare.ParameterList.Parameters.Count != 0 || prepare.ReturnType.ToString() is not ("bool" or "void"))
                    throw new InvalidOperationException("Prepare signature requires an explicit unsupported adapter: " + MetadataName(type));
                prepareBridge = "__EHRStaticPrepare";
                string body = prepare.ReturnType.ToString() == "void" ? "{ " + prepare.Identifier.Text + "(); return true; }" : "=> " + prepare.Identifier.Text + "();";
                edits.Add(new(classDecl.SyntaxTree.FilePath, classDecl.CloseBraceToken.SpanStart, classDecl.CloseBraceToken.SpanStart,
                    "\n    internal static bool " + prepareBridge + "() " + body + "\n", "static_Prepare_bridge"));
            }
            var dynamicTargets = DynamicTargets(methods);
            foreach (MethodDeclarationSyntax method in callbackMethods)
            {
                AttributeSyntax[] methodAttrs = MethodAttributes(method);
                string? kind = methodAttrs.Select(AttributeName).FirstOrDefault(n => n is "HarmonyPrefix" or "HarmonyPostfix" or "HarmonyFinalizer")?.Replace("Harmony", "", StringComparison.Ordinal)
                    ?? (method.Identifier.ValueText is "Prefix" or "Postfix" or "Finalizer" ? method.Identifier.ValueText : null);
                if (kind == null) throw new InvalidOperationException("Unclassified callback.");
                string returnType = method.ReturnType.ToString();
                bool supportedReturn = kind == "Prefix" ? returnType is "bool" or "void" : kind == "Postfix" ? returnType == "void" : returnType is "Exception" or "System.Exception" or "void";
                string[] unsupported = (!method.Modifiers.Any(SyntaxKind.StaticKeyword) ? new[] { "nonstatic_callback" } : Array.Empty<string>())
                    .Concat(method.TypeParameterList != null ? new[] { "generic_callback" } : [])
                    .Concat(!supportedReturn ? new[] { "unsupported_callback_return_form" } : [])
                    .Concat(method.ParameterList.Parameters.Any(p => p.Type is PointerTypeSyntax or FunctionPointerTypeSyntax || p.Type?.ToString().Contains("Span<", StringComparison.Ordinal) == true) ? new[] { "nonboxable_callback_parameter" } : []).ToArray();
                if (unsupported.Length != 0) { rejected.Add(new { type = MetadataName(type), method = method.Identifier.ValueText, reasons = unsupported }); continue; }
                string classId = MetadataName(type), callbackId = classId + "::" + method.Identifier.ValueText + "#" + index;
                string bridge = "__EHRStaticCallback_" + index;
                string wrapper = CallbackBridge(method, kind, classId, bridge);
                edits.Add(new(classDecl.SyntaxTree.FilePath, classDecl.CloseBraceToken.SpanStart, classDecl.CloseBraceToken.SpanStart, wrapper, "direct_callback_bridge"));
                var info = MergePatchInfo(classAttrs, methodAttrs);
                PatchInfo[] alternatives = MergeHarmonyXTargetAlternatives(classAttrs, methodAttrs);
                StaticTargetRow[] targets = dynamicTargets.Length > 0 ? dynamicTargets : alternatives
                    .Where(p => p.TypeName.Length > 0 && (p.MemberName.Length > 0 || p.MethodKind is "Constructor" or "StaticConstructor"))
                    .Select(ResolveTarget).ToArray();
                bool affects = kind == "Prefix" && (returnType != "void" || method.ParameterList.Parameters.Any(p => p.Modifiers.Any(t => t.IsKind(SyntaxKind.RefKeyword) || t.IsKind(SyntaxKind.OutKeyword) || t.IsKind(SyntaxKind.InKeyword))));
                string[] requirements = method.ParameterList.Parameters.Select(p => p.Identifier.ValueText + ":" + p.Type + (p.Modifiers.Count > 0 ? ":" + string.Join(" ", p.Modifiers.Select(t => t.Text)) : "")).ToArray();
                rows.Add(new(callbackId, classId, method.Identifier.ValueText, kind, info.Priority, index, affects, assemblyScan, targets, requirements,
                    method.SyntaxTree.FilePath, method.GetLocation().GetLineSpan().StartLinePosition.Line + 1, "native_target_and_ABI_unbound"));
                b.AppendLine("        new EHRStaticPatchDescriptor(" + Quote(callbackId) + ", " + Quote(classId) + ", \"com.gurge44.endlesshostroles\", EHRStaticPatchKind." + kind + ", " + info.Priority + ", " + index + ", " + (affects ? "true" : "false") + ", " + (assemblyScan ? "true" : "false") + ", " + StringArray(info.Before) + ", " + StringArray(info.After) + ", new EHRStaticTargetSpec[] { " + string.Join(", ", targets.Select(TargetConstructor)) + " }, " + CsName(type) + "." + bridge + ", " + (prepareBridge != null ? CsName(type) + "." + prepareBridge : "null") + "),");
                index++;
            }
        }
        b.AppendLine("    };\n    internal static readonly EHRStaticRegistration Registration = new EHRStaticRegistration(Descriptors);\n}\n");
        var registrationEdits = new List<object>();
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            foreach (InvocationExpressionSyntax call in tree.GetRoot().DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                string normalized = Normalize(call.ToString());
                string? replacement = normalized switch
                {
                    "Harmony.PatchAll(Assembly.GetExecutingAssembly())" => "EHRStaticPatchCatalog.Registration.RequestAssembly()",
                    "Main.Instance.Harmony.UnpatchSelf()" => "EHRStaticPatchCatalog.Registration.DisableOwner(\"com.gurge44.endlesshostroles\")",
                    _ => null
                };
                if (normalized.StartsWith("Harmony.PatchAll(typeof(", StringComparison.Ordinal)
                    && call.ArgumentList.Arguments.SingleOrDefault()?.Expression is TypeOfExpressionSyntax typeExpression)
                {
                    ITypeSymbol? target = compilation.GetSemanticModel(tree).GetTypeInfo(typeExpression.Type).Type;
                    if (target is not INamedTypeSymbol named || target.TypeKind == TypeKind.Error)
                        throw new InvalidOperationException("Explicit patch class could not be semantically resolved.");
                    replacement = "EHRStaticPatchCatalog.Registration.RequestClass(" + Quote(MetadataName(named)) + ")";
                }
                if (replacement == null) continue;
                edits.Add(new(tree.FilePath, call.SpanStart, call.Span.End, replacement, "static_registration_request"));
                registrationEdits.Add(new { file = tree.FilePath, original = call.ToString(), replacement });
            }
        }
        var selectors = rows.SelectMany(r => r.Targets.Select(t => (callback: r.Id, target: t)))
            .GroupBy(item => string.Join("|", item.target.Image ?? "", item.target.TypeName, item.target.MemberName, item.target.MethodKind, string.Join(",", item.target.ArgumentTypes)))
            .Select(g => new { selectorId = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(g.Key))).ToLowerInvariant()[..20],
                image = g.First().target.Image, declaringType = g.First().target.TypeName, methodName = g.First().target.MemberName,
                methodKind = g.First().target.MethodKind, parameterTypes = g.First().target.ArgumentTypes,
                parameterNames = g.First().target.ParameterNames, isStatic = g.First().target.IsStatic,
                returnType = g.First().target.ReturnType, resolutionStatus = g.First().target.ResolutionStatus,
                managedDeclaringType = g.First().target.ManagedDeclaringType, managedImage = g.First().target.ManagedImage,
                candidateSignatures = g.First().target.CandidateSignatures,
                callbackIds = g.Select(item => item.callback).Distinct().ToArray() }).ToArray();
        var sourceTypes = rows.SelectMany(r => r.Targets)
            .GroupBy(t => string.Join("|",t.Image ?? "",t.TypeName,t.MemberName,t.MethodKind,string.Join(",",t.ArgumentTypes)))
            .Select(g => new {
                selectorId = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(g.Key))).ToLowerInvariant()[..20],
                resolutionStatus=g.First().ResolutionStatus,
                instanceType=g.First().SourceInstanceType,
                returnType=g.First().SourceReturnType,
                parameterTypes=g.First().SourceParameterTypes,
                parameterRefKinds=g.First().SourceParameterRefKinds
            }).ToArray();
        return new(b.ToString(), ApplyEdits(edits), new { schema = "ehr.static-direct-dispatch.v1", upstreamCommit = pin, compileProfile = profile,
            callbackCount = rows.Count, callbacksByKind = rows.GroupBy(r => r.Kind).ToDictionary(g => g.Key, g => g.Count()),
            rows, rejectedManagedBridgeForms = rejected, sourceEdits = edits.Distinct().ToArray(), registrationEdits,
            nativeBinding = "Unavailable: no native resolver, address binding, ABI adapter or thunk is produced by this generator.",
            semanticScope = new[] {
                "Direct source callback calls with per-invocation state, ref/out/in argument/result/instance writeback, HarmonyX 2.10.2 all-prefix execution with bool returns ANDed to skip only the original, postfix and finalizer dispatch.",
                "Priority is descending then source registration index, with acyclic Before/After dependency ordering. Pinned EHR has no dependency cycles; future cycles are explicitly unsupported.",
                "Prepare is called once for class registration and once per resolved original target; all pinned Prepare methods are static zero-argument bool.",
                "Exact HarmonyX 2.10.2 AttributePatch composition: incomplete annotations merge; multiple complete method targets branch independently; one complete target merges normally. Method details override class fields.",
                "Static TargetMethods lists expand at build time; coroutine MoveNext specs require the actual native metadata resolver and are never guessed from PC generated names.",
                "Runtime optional external-map registrations are not activated by this catalog; they require separate versioned external bindings."
            },
            primarySemanticReferences = new[] { "https://github.com/BepInEx/HarmonyX/blob/v2.10.2/Harmony/Public/Patching/HarmonyManipulator.cs", "https://github.com/BepInEx/HarmonyX/blob/v2.10.2/Harmony/Public/PatchClassProcessor.cs", "https://github.com/BepInEx/HarmonyX/blob/v2.10.2/Harmony/Public/HarmonyMethod.cs", "https://github.com/BepInEx/HarmonyX/blob/v2.10.2/Harmony/Internal/PatchModels.cs", "https://github.com/BepInEx/HarmonyX/blob/v2.10.2/Harmony/Internal/PatchSorter.cs" }},
            new { schema = "ehr.native-target-selectors.v1", upstreamCommit = pin, compileProfile = profile,
                scope = "Semantically resolved PC IL2CPP game-binding selectors; native iOS metadata/address/ABI validation remains required. CoroutineMoveNext entries identify the factory and require actual iterator-body resolution.",
                selectors }, new { schema="ehr.source-patch-clr-types.v1",upstreamCommit=pin,compileProfile=profile,
                    scope="Exact compile-time CLR types from the same resolved target symbols; not native ABI or runtime availability evidence.",selectors=sourceTypes });

        void MakeAccessible(INamedTypeSymbol type)
        {
            foreach (INamedTypeSymbol item in Parents(type).Reverse().Append(type))
            {
                if (item.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal) continue;
                if (declarations[item] is not TypeDeclarationSyntax declaration) throw new InvalidOperationException("Unsupported patch ancestor.");
                SyntaxToken[] visibility = declaration.Modifiers.Where(t => t.IsKind(SyntaxKind.PrivateKeyword) || t.IsKind(SyntaxKind.ProtectedKeyword)).ToArray();
                if (visibility.Length > 1) throw new InvalidOperationException("Combined patch type accessibility requires explicit handling.");
                if (visibility.Length == 1) edits.Add(new(declaration.SyntaxTree.FilePath, visibility[0].SpanStart, visibility[0].Span.End, "internal", "patch_type_source_access"));
                else
                {
                    int position = declaration.Modifiers.Count > 0 ? declaration.Modifiers[0].SpanStart : declaration.Keyword.SpanStart;
                    edits.Add(new(declaration.SyntaxTree.FilePath, position, position, "internal ", "patch_type_source_access"));
                }
            }
        }
    }

    static string TargetConstructor(StaticTargetRow t) => "new EHRStaticTargetSpec(" + Quote(t.TypeName) + ", " + Quote(t.MemberName) + ", " + Quote(t.MethodKind)
        + ", " + StringArray(t.ArgumentTypes) + ", " + (t.ExactArgumentTypes ? "true" : "false") + ", " + (t.Image == null ? "null" : Quote(t.Image))
        + ", " + (t.ReturnType == null ? "null" : Quote(t.ReturnType)) + ", " + (t.IsStatic.HasValue ? (t.IsStatic.Value ? "true" : "false") : "null")
        + ", " + StringArray(t.ParameterNames ?? []) + ", " + Quote(t.ResolutionStatus) + ")";

    static string StringArray(IEnumerable<string> values) => "new string[] { " + string.Join(", ", values.Select(Quote)) + " }";

    static string CallbackBridge(MethodDeclarationSyntax method, string kind, string classId, string bridge)
    {
        var b = new StringBuilder("\n    internal static void " + bridge + "(global::EHR.EHRStaticPatchFrame __ehrFrame)\n    {\n");
        var calls = new List<string>();
        var writes = new List<string>();
        int i = 0;
        foreach (ParameterSyntax parameter in method.ParameterList.Parameters)
        {
            string name = parameter.Identifier.ValueText, type = parameter.Type?.ToString() ?? throw new InvalidOperationException("Untyped callback parameter.");
            string local = "__ehrp" + i, read, write = "";
            AttributeSyntax? argument = parameter.AttributeLists.SelectMany(a => a.Attributes).FirstOrDefault(a => AttributeName(a) == "HarmonyArgument");
            string selector = argument?.ArgumentList?.Arguments.FirstOrDefault()?.Expression.ToString() ?? Quote(name);
            bool byref = parameter.Modifiers.Any(t => t.IsKind(SyntaxKind.RefKeyword) || t.IsKind(SyntaxKind.OutKeyword));
            if (name == "__instance") { read = "__ehrFrame.GetInstance<" + type + ">()"; write = "__ehrFrame.Instance = " + local + ";"; }
            else if (name == "__result") { read = "__ehrFrame.GetResult<" + type + ">()"; write = "__ehrFrame.Result = " + local + ";"; }
            else if (name == "__state") { read = "__ehrFrame.GetState<" + type + ">(" + Quote(classId) + ")"; write = "__ehrFrame.SetState(" + Quote(classId) + ", " + local + ");"; }
            else if (name == "__exception") { read = "__ehrFrame.Exception!"; write = "__ehrFrame.Exception = " + local + ";"; }
            else if (name == "__runOriginal") { read = "__ehrFrame.RunOriginal"; write = "__ehrFrame.RunOriginal = " + local + ";"; }
            else if (name.StartsWith("___", StringComparison.Ordinal)) { read = "__ehrFrame.GetField<" + type + ">(" + Quote(name[3..]) + ")"; write = "__ehrFrame.SetField(" + Quote(name[3..]) + ", " + local + ");"; }
            else if (name.StartsWith("__", StringComparison.Ordinal) && int.TryParse(name[2..], out int numeric)) { selector = numeric.ToString(); read = "__ehrFrame.GetArgument<" + type + ">(" + selector + ")"; write = "__ehrFrame.SetArgument(" + selector + ", " + local + ");"; }
            else { read = "__ehrFrame.GetArgument<" + type + ">(" + selector + ")"; write = "__ehrFrame.SetArgument(" + selector + ", " + local + ");"; }
            if (parameter.Modifiers.Any(SyntaxKind.OutKeyword)) read = "default!";
            b.AppendLine("        " + type + " " + local + " = " + read + ";");
            string modifier = parameter.Modifiers.Any(SyntaxKind.OutKeyword) ? "out " : parameter.Modifiers.Any(SyntaxKind.RefKeyword) ? "ref " : parameter.Modifiers.Any(SyntaxKind.InKeyword) ? "in " : "";
            calls.Add(modifier + local);
            if (byref) writes.Add(write);
            i++;
        }
        bool returnsBool = kind == "Prefix" && method.ReturnType.ToString() == "bool";
        bool returnsException = kind == "Finalizer" && method.ReturnType.ToString() != "void";
        if (returnsBool) b.AppendLine("        bool __ehrReturn = default;");
        if (returnsException) b.AppendLine("        global::System.Exception __ehrReturn = default!;");
        b.AppendLine("        try\n        {");
        string call = method.Identifier.Text + "(" + string.Join(", ", calls) + ")";
        if (returnsBool || returnsException) b.AppendLine("            __ehrReturn = " + call + ";");
        else b.AppendLine("            " + call + ";");
        b.AppendLine("        }\n        finally\n        {");
        foreach (string write in writes) b.AppendLine("            " + write);
        b.AppendLine("        }");
        // Native Harmony references mutate their storage during the call;
        // returned control/exception values are assigned only after it returns.
        if (returnsBool) b.AppendLine("        __ehrFrame.RunOriginal = __ehrFrame.RunOriginal && __ehrReturn;");
        if (returnsException) b.AppendLine("        __ehrFrame.Exception = __ehrReturn;");
        b.AppendLine("    }\n");
        return b.ToString();
    }

    PatchInfo MergePatchInfo(AttributeSyntax[] classAttrs, AttributeSyntax[] methodAttrs)
    {
        PatchInfo result = new();
        Apply(classAttrs); Apply(methodAttrs);
        if (result.Priority < 0) result.Priority = 400;
        return result;
        void Apply(IEnumerable<AttributeSyntax> attributes)
        {
            foreach (AttributeSyntax attribute in attributes)
            {
                ExpressionSyntax[] args = attribute.ArgumentList?.Arguments.Select(a => a.Expression).ToArray() ?? [];
                string name = AttributeName(attribute);
                if (name == "HarmonyPatch")
                {
                    var argumentTypes = new List<string>();
                    var argumentSymbols = new List<ITypeSymbol>();
                    bool foundArgs = false;
                    for (int i = 0; i < args.Length; i++)
                    {
                        if (args[i] is TypeOfExpressionSyntax type)
                        {
                            ITypeSymbol? symbol = compilation.GetSemanticModel(type.SyntaxTree).GetTypeInfo(type.Type).Type;
                            if (i == 0) { result.TypeName = type.Type.ToString(); result.TypeSymbol = symbol; }
                            else { argumentTypes.Add(type.Type.ToString()); if (symbol != null) argumentSymbols.Add(symbol); foundArgs = true; }
                        }
                        else if (args[i] is InvocationExpressionSyntax { Expression: IdentifierNameSyntax { Identifier.ValueText: "nameof" } } nameofCall)
                            result.MemberName = nameofCall.ArgumentList.Arguments[0].Expression.GetLastToken().ValueText;
                        else if (args[i] is LiteralExpressionSyntax literal && literal.IsKind(SyntaxKind.StringLiteralExpression)) result.MemberName = literal.Token.ValueText;
                        else if (args[i] is MemberAccessExpressionSyntax member && member.Expression.ToString() == "MethodType") result.MethodKind = member.Name.Identifier.ValueText;
                        else if (args[i].DescendantNodesAndSelf().OfType<TypeOfExpressionSyntax>().Any())
                        {
                            foreach (TypeOfExpressionSyntax part in args[i].DescendantNodesAndSelf().OfType<TypeOfExpressionSyntax>())
                            { argumentTypes.Add(part.Type.ToString()); ITypeSymbol? symbol = compilation.GetSemanticModel(part.SyntaxTree).GetTypeInfo(part.Type).Type; if (symbol != null) argumentSymbols.Add(symbol); }
                            foundArgs = true;
                        }
                        else throw new InvalidOperationException("Unsupported HarmonyPatch argument: " + args[i]);
                    }
                    if (foundArgs) { result.ArgumentTypes = argumentTypes.ToArray(); result.ArgumentSymbols = argumentSymbols.ToArray(); }
                }
                if (name == "HarmonyPriority")
                {
                    string value = args.Single().ToString();
                    int priority = int.TryParse(value, out int number) ? number : value.Split('.').Last() switch
                    { "First" => 800, "VeryHigh" => 700, "High" => 600, "HigherThanNormal" => 500, "Normal" => 400, "LowerThanNormal" => 300, "Low" => 200, "VeryLow" => 100, "Last" => 0, _ => throw new InvalidOperationException("Unknown Harmony priority") };
                    result.Priority = priority;
                }
                if (name is "HarmonyBefore" or "HarmonyAfter")
                {
                    string[] owners = args.SelectMany(a => a.DescendantNodesAndSelf().OfType<LiteralExpressionSyntax>()).Where(l => l.IsKind(SyntaxKind.StringLiteralExpression)).Select(l => l.Token.ValueText).ToArray();
                    if (name == "HarmonyBefore") result.Before = owners; else result.After = owners;
                }
            }
        }
    }

    PatchInfo[] MergeHarmonyXTargetAlternatives(AttributeSyntax[] classAttrs, AttributeSyntax[] methodAttrs)
    {
        // Matches the pinned HarmonyX AttributePatch.Create collectIncomplete
        // policy; standard Harmony's one-target merge is insufficient here.
        PatchInfo container = MergePatchInfo(classAttrs, []);
        bool collectIncomplete = container.TypeName.Length != 0;
        var incomplete = new List<AttributeSyntax>();
        var complete = new List<(AttributeSyntax attribute, PatchInfo info)>();
        foreach (AttributeSyntax attribute in methodAttrs)
        {
            PatchInfo item = MergePatchInfo([], [attribute]);
            if ((collectIncomplete || item.TypeName.Length != 0) && item.MemberName.Length != 0) complete.Add((attribute, item));
            else incomplete.Add(attribute);
        }
        PatchInfo baseline = MergePatchInfo([], incomplete.ToArray());
        bool Same(PatchInfo a, PatchInfo c) => a.TypeName == c.TypeName && a.MemberName == c.MemberName
            && (a.ArgumentTypes ?? []).SequenceEqual(c.ArgumentTypes ?? [], StringComparer.Ordinal);
        complete = complete.Where(item => !Same(item.info, baseline)).ToList();
        return complete.Count > 1
            ? complete.Select(item => MergePatchInfo(classAttrs, incomplete.Append(item.attribute).ToArray())).ToArray()
            : [MergePatchInfo(classAttrs, methodAttrs)];
    }

    StaticTargetRow[] DynamicTargets(MethodDeclarationSyntax[] methods)
    {
        MethodDeclarationSyntax[] resolvers = methods.Where(m => m.Identifier.ValueText is "TargetMethod" or "TargetMethods" || MethodAttributes(m).Any(a => AttributeName(a) is "HarmonyTargetMethod" or "HarmonyTargetMethods")).ToArray();
        if (resolvers.Length == 0) return [];
        var result = new List<StaticTargetRow>();
        foreach (InvocationExpressionSyntax call in resolvers.SelectMany(m => m.DescendantNodes().OfType<InvocationExpressionSyntax>()))
        {
            string name = call.Expression.GetLastToken().ValueText;
            if (call.Expression is MemberAccessExpressionSyntax access) name = access.Name.Identifier.ValueText;
            if (name == "Method" && call.Expression.ToString().StartsWith("AccessTools.", StringComparison.Ordinal))
            {
                if (call.ArgumentList.Arguments.Count != 2 || call.ArgumentList.Arguments[0].Expression is not TypeOfExpressionSyntax target
                    || call.ArgumentList.Arguments[1].Expression is not InvocationExpressionSyntax { Expression: IdentifierNameSyntax { Identifier.ValueText: "nameof" } } named)
                    throw new InvalidOperationException("Unsupported build-time AccessTools.Method resolver form.");
                PatchInfo info = new() { TypeName = target.Type.ToString(),
                    TypeSymbol = compilation.GetSemanticModel(target.SyntaxTree).GetTypeInfo(target.Type).Type,
                    MemberName = named.ArgumentList.Arguments.Single().Expression.GetLastToken().ValueText };
                if (info.TypeName.Length == 0 || info.MemberName.Length == 0) throw new InvalidOperationException("Unresolved build-time TargetMethods entry.");
                result.Add(ResolveTarget(info));
            }
            if (name == "GetStateMachineMoveNext" && call.Expression is MemberAccessExpressionSyntax { Name: GenericNameSyntax generic })
            {
                string targetType = generic.TypeArgumentList.Arguments.Single().ToString();
                string member = call.ArgumentList.Arguments.Single().Expression.DescendantNodesAndSelf().OfType<MemberAccessExpressionSyntax>().Last().Name.Identifier.ValueText;
                result.Add(ResolveTarget(new PatchInfo { TypeName = targetType, MemberName = member, MethodKind = "CoroutineMoveNext",
                    TypeSymbol = compilation.GetSemanticModel(generic.SyntaxTree).GetTypeInfo(generic.TypeArgumentList.Arguments.Single()).Type }));
            }
        }
        if (result.Count == 0) throw new InvalidOperationException("Unsupported dynamic target resolver body.");
        return result.ToArray();
    }

    static string NativeTypeName(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol array) return NativeTypeName(array.ElementType) + "[" + new string(',', array.Rank - 1) + "]";
        if (type is IPointerTypeSymbol pointer) return NativeTypeName(pointer.PointedAtType) + "*";
        if (type is INamedTypeSymbol named)
        {
            string ns = named.ContainingNamespace.IsGlobalNamespace ? "" : named.ContainingNamespace.ToDisplayString();
            if (ns == "Il2CppInterop.Runtime.InteropTypes.Arrays")
            {
                if (named.Name is "Il2CppReferenceArray" or "Il2CppStructArray" && named.TypeArguments.Length == 1)
                    return NativeTypeName(named.TypeArguments[0]) + "[]";
                if (named.Name == "Il2CppStringArray") return "System.String[]";
            }
            if (ns == "Il2CppSystem" || ns.StartsWith("Il2CppSystem.", StringComparison.Ordinal)) ns = ns[6..];
            string head = named.ContainingType != null ? NativeTypeName(named.ContainingType) + "+" + named.Name : (ns.Length > 0 ? ns + "." : "") + named.Name;
            return named.TypeArguments.Length > 0 ? head + "<" + string.Join(",", named.TypeArguments.Select(NativeTypeName)) + ">" : head;
        }
        return type.ToDisplayString();
    }

    StaticTargetRow ResolveTarget(PatchInfo info)
    {
        if (info.TypeSymbol is not INamedTypeSymbol type || type.TypeKind == TypeKind.Error)
            return new(info.TypeName, info.MemberName, info.MethodKind, info.ArgumentTypes ?? [], info.ArgumentTypes != null,
                ResolutionStatus: "unresolved_declaring_type");
        string typeName = NativeTypeName(type), managedType = MetadataName(type), managedImage = type.ContainingAssembly.Name;
        string image = managedImage.StartsWith("Il2Cpp", StringComparison.Ordinal) ? managedImage[6..] : managedImage;
        IEnumerable<IMethodSymbol> candidates = info.MethodKind switch
        {
            "Getter" => type.GetMembers(info.MemberName).OfType<IPropertySymbol>().Select(p => p.GetMethod).OfType<IMethodSymbol>(),
            "Setter" => type.GetMembers(info.MemberName).OfType<IPropertySymbol>().Select(p => p.SetMethod).OfType<IMethodSymbol>(),
            "Constructor" => type.InstanceConstructors,
            "StaticConstructor" => type.StaticConstructors,
            _ => type.GetMembers(info.MemberName).OfType<IMethodSymbol>()
        };
        if (info.ArgumentSymbols != null)
            candidates = candidates.Where(m => m.Parameters.Length == info.ArgumentSymbols.Length && m.Parameters.Select(p => p.Type).Zip(info.ArgumentSymbols).All(pair => SymbolEqualityComparer.Default.Equals(pair.First, pair.Second)));
        IMethodSymbol[] found = candidates.ToArray();
        string[] signatures = found.Select(m => m.MetadataName + "(" + string.Join(",", m.Parameters.Select(p => NativeTypeName(p.Type) + (p.RefKind == RefKind.None ? "" : "&"))) + ")").ToArray();
        if (found.Length != 1)
            return new(typeName, info.MemberName, info.MethodKind, info.ArgumentSymbols?.Select(NativeTypeName).ToArray() ?? [], info.ArgumentSymbols != null,
                image, managedImage, managedType, ResolutionStatus: found.Length == 0 ? "unresolved_declared_member" : "ambiguous_declared_overload", CandidateSignatures: signatures);
        IMethodSymbol method = found[0];
        return new(typeName, method.MetadataName, info.MethodKind,
            method.Parameters.Select(p => NativeTypeName(p.Type) + (p.RefKind == RefKind.None ? "" : "&")).ToArray(), true,
            image, managedImage, managedType, method.Parameters.Select(p => p.Name).ToArray(), method.IsStatic, NativeTypeName(method.ReturnType),
            info.MethodKind == "CoroutineMoveNext" ? "factory_resolved_actual_MoveNext_unbound" : "resolved_managed_reference_signature", signatures,
            CsName(type), CsName(method.ReturnType),method.Parameters.Select(p=>CsName(p.Type)).ToArray(),method.Parameters.Select(p=>p.RefKind.ToString()).ToArray());
    }
}

