using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

sealed partial class Model
{
    static string Quote(string value) => System.Text.Json.JsonSerializer.Serialize(value);

    public BootstrapOutput GenerateBootstrap(string pin, string profile)
    {
        List<SourceEdit> edits = [];
        var rejectedRoots = new List<object>();
        var rooted = new List<INamedTypeSymbol>();
        foreach (INamedTypeSymbol type in Types)
        {
            string? reason = declarations[type] is ExtensionBlockDeclarationSyntax ? "CSharp_extension_block_synthetic_container_not_an_addressable_source_type"
                : type.Arity != 0 || Parents(type).Any(t => t.Arity != 0) ? "open_generic_source_definition_not_required_by_bootstrap_groups"
                : !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly) ? "private_or_protected_nested_helper_not_required_by_bootstrap_groups" : null;
            if (reason != null) rejectedRoots.Add(new { type = MetadataName(type), reason });
            else rooted.Add(type);
        }
        var b = new StringBuilder("// <auto-generated />\n// EHR source bootstrap: " + pin + "; " + profile + ". Does not bind the native game.\n#nullable enable\nnamespace EHR;\ninternal static class EHRSourceBootstrap\n{\n");
        b.AppendLine("    internal static global::System.Type[] SourceDeclaredTypes() => new global::System.Type[]\n    {");
        foreach (INamedTypeSymbol type in rooted) b.AppendLine("        typeof(" + CsName(type) + "),");
        b.AppendLine("    };\n");
        List<Group> groups = Groups();
        Group hns = groups.Single(g => g.Id == "IHideAndSeekRole");
        if (hns.Rows.GroupBy(r => r.Name).Any(g => g.Count() != 1)) throw new InvalidOperationException("Ambiguous HnS source names.");
        b.AppendLine("    internal static global::System.Type FindHnsRoleType(string name) => name switch\n    {");
        foreach (Row row in hns.Rows) b.AppendLine("        " + Quote(row.Name) + " => typeof(" + row.CSharpType + "),");
        b.AppendLine("        _ => throw new global::System.InvalidOperationException(\"Unregistered HnS role name: \" + name)\n    };\n");

        string[] methodNames = ["OnMeetingShapeshift", "OnJudge", "OnPet", "OnCheckMurder", "OnVote", "ManipulateGameEndCheckCrew"];
        var methodRows = new List<object>();
        b.AppendLine("    internal static bool DeclaresRoleMethod(global::System.Type type, string name)\n    {\n        switch (name)\n        {");
        foreach (string name in methodNames)
        {
            b.AppendLine("            case " + Quote(name) + ":");
            foreach (Row row in groups.Single(g => g.Id == "RoleBase").Rows)
            {
                INamedTypeSymbol type = Types.Single(t => MetadataName(t) == row.Type);
                IMethodSymbol[] declared = type.GetMembers(name).OfType<IMethodSymbol>().Where(m => m.DeclaredAccessibility == Accessibility.Public).ToArray();
                if (declared.Length > 1) throw new InvalidOperationException("Ambiguous source role method: " + row.Type + "." + name);
                if (declared.Length == 0) continue;
                b.AppendLine("                if (type == typeof(" + row.CSharpType + ")) return true;");
                methodRows.Add(new { type = row.Type, method = name });
            }
            b.AppendLine("                return false;");
        }
        b.AppendLine("            default: throw new global::System.NotSupportedException(\"Unregistered role method query: \" + name);\n        }\n    }\n");

        var rpcRows = new List<object>();
        b.AppendLine("    internal static void ReceiveRoleRpc(global::EHR.Roles.RoleBase role, global::Hazel.MessageReader reader)\n    {\n        if (role is null) throw new global::System.ArgumentNullException(nameof(role));\n        global::System.Type type = role.GetType();\n        try\n        {");
        foreach (Row row in groups.Single(g => g.Id == "RoleBase").Rows)
        {
            INamedTypeSymbol type = Types.Single(t => MetadataName(t) == row.Type);
            IMethodSymbol[] methods = [];
            for (INamedTypeSymbol? ancestor = type; ancestor != null && methods.Length == 0; ancestor = ancestor.BaseType)
                methods = ancestor.GetMembers("ReceiveRPC").OfType<IMethodSymbol>().Where(m => m.DeclaredAccessibility == Accessibility.Public).ToArray();
            string status = methods.Length == 0 ? "absent_upstream_noop" : methods.Length > 1 ? "ambiguous_upstream_method"
                : methods[0].Parameters.Length == 1 && methods[0].Parameters[0].Type.Name == "MessageReader" && methods[0].ReturnsVoid && methods[0].TypeParameters.Length == 0 ? "explicit_direct_call" : "unsupported_upstream_signature";
            b.Append("            if (type == typeof(" + row.CSharpType + ")) { ");
            if (status == "explicit_direct_call") b.Append((methods[0].IsStatic ? row.CSharpType : "((" + row.CSharpType + ")role)") + ".ReceiveRPC(reader); ");
            else if (status == "ambiguous_upstream_method") b.Append("throw new global::System.Reflection.AmbiguousMatchException(\"Ambiguous upstream ReceiveRPC\"); ");
            else if (status == "unsupported_upstream_signature") b.Append("throw new global::System.NotSupportedException(\"Unbound upstream ReceiveRPC signature\"); ");
            b.AppendLine(status.Contains("upstream_") && status != "absent_upstream_noop" ? "}" : "return; }");
            rpcRows.Add(new { type = row.Type, status, isStatic = methods.Length == 1 && methods[0].IsStatic });
        }
        b.AppendLine("        }\n        catch (global::System.Exception error) { throw new global::System.Reflection.TargetInvocationException(error); }\n        throw new global::System.NotSupportedException(\"Unregistered runtime role type\");\n    }\n");

        string[] settings = ["AbilityUseGainWithEachKill", "AbilityUseGainWithEachTaskCompleted", "AbilityChargesWhenFinishedTasks"];
        var fieldRows = new List<object>();
        b.AppendLine("    private sealed class FieldEntry\n    {\n        internal readonly string TypeName, FieldName;\n        internal readonly global::System.Func<object?> Read;\n        internal FieldEntry(string typeName, string fieldName, global::System.Func<object?> read) { TypeName = typeName; FieldName = fieldName; Read = read; }\n    }\n    private static readonly FieldEntry[] SettingFields = new FieldEntry[]\n    {");
        foreach (INamedTypeSymbol type in Types)
        {
            foreach (IFieldSymbol field in type.GetMembers().OfType<IFieldSymbol>().Where(f => f.IsStatic && settings.Any(s => f.Name.Contains(s, StringComparison.Ordinal))))
            {
                if (!rooted.Any(t => EqualsType(t, type))) throw new InvalidOperationException("Required setting field belongs to inaccessible source type: " + MetadataName(type) + "." + field.Name);
                if (field.IsImplicitlyDeclared) throw new InvalidOperationException("Required implicit setting field needs an explicit source accessor: " + field.Name);
                SyntaxNode declaration = field.DeclaringSyntaxReferences.Single().GetSyntax();
                FieldDeclarationSyntax owner = declaration.AncestorsAndSelf().OfType<FieldDeclarationSyntax>().First();
                if (field.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal))
                {
                    SyntaxToken visibility = owner.Modifiers.FirstOrDefault(t => t.IsKind(SyntaxKind.PrivateKeyword) || t.IsKind(SyntaxKind.ProtectedKeyword));
                    if (visibility.RawKind != 0) edits.Add(new(owner.SyntaxTree.FilePath, visibility.SpanStart, visibility.Span.End, "internal", "setting_field_source_access"));
                    else edits.Add(new(owner.SyntaxTree.FilePath, owner.SpanStart, owner.SpanStart, "internal ", "setting_field_source_access"));
                }
                b.AppendLine("        new FieldEntry(" + Quote(type.Name) + ", " + Quote(field.Name) + ", static () => (object?)" + CsName(type) + "." + field.Name + "),");
                fieldRows.Add(new { type = MetadataName(type), name = field.Name, source = locations[type] });
            }
        }
        b.AppendLine("    };\n    internal static float ReadRoleSetting(string role, string setting)\n    {\n        if (setting != \"AbilityUseGainWithEachKill\" && setting != \"AbilityUseGainWithEachTaskCompleted\" && setting != \"AbilityChargesWhenFinishedTasks\") throw new global::System.NotSupportedException(\"Unregistered setting-field query: \" + setting);\n        FieldEntry? selected = null;\n        string key = role + setting;\n        foreach (FieldEntry entry in SettingFields) if (entry.FieldName == key) { selected = entry; break; }\n        if (selected is null) foreach (FieldEntry entry in SettingFields) if (entry.TypeName == role && entry.FieldName.Contains(setting)) { selected = entry; break; }\n        return selected?.Read() is global::EHR.OptionItem value ? value.GetFloat() : float.MaxValue;\n    }\n}\n");

        ReplaceInvocation("Main.cs", "Assembly.GetExecutingAssembly().GetTypes()", "EHRSourceBootstrap.SourceDeclaredTypes()");
        ReplaceInvocation("Gamemodes/CustomHnS.cs", "Main.AllTypes.First(t => t.Name == role.ToString())", "EHRSourceBootstrap.FindHnsRoleType(role.ToString())");
        ReplaceInvocation("Modules/RPC.cs", "r.GetType().GetMethod(\"ReceiveRPC\")?.Invoke(r, [reader])", "EHRSourceBootstrap.ReceiveRoleRpc(r, reader)");
        foreach (string path in new[] { "Modules/CustomRolesHelper.cs", "Roles/Standard/Coven/Dreamweaver.cs", "Roles/Standard/Coven/VoodooMaster.cs", "Patches/HudPatch.cs" })
        {
            SyntaxTree tree = compilation.SyntaxTrees.Single(t => t.FilePath == path);
            foreach (BinaryExpressionSyntax binary in tree.GetRoot().DescendantNodes().OfType<BinaryExpressionSyntax>())
            {
                string normalized = Normalize(binary.ToString());
                foreach (string method in methodNames)
                {
                    string a = Normalize("type.GetMethod(\"" + method + "\")?.DeclaringType == type");
                    string c = Normalize("type.GetMethod(\"" + method + "\").DeclaringType == type");
                    if (normalized == a || normalized == c) edits.Add(new(path, binary.SpanStart, binary.Span.End,
                        "EHRSourceBootstrap.DeclaresRoleMethod(type, " + Quote(method) + ")", "concrete_role_method_query"));
                }
            }
        }
        SyntaxTree utils = compilation.SyntaxTrees.Single(t => t.FilePath == "Modules/Utils.cs");
        MethodDeclarationSyntax settingMethod = utils.GetRoot().DescendantNodes().OfType<MethodDeclarationSyntax>().Single(m => m.Identifier.ValueText == "GetSettingNameAndValueForRole");
        if (settingMethod.Body == null) throw new InvalidOperationException("Unexpected setting method shape.");
        edits.Add(new(utils.FilePath, settingMethod.Body.SpanStart, settingMethod.Body.Span.End,
            "{ var cacheKey = (role, settingName); if (CachedRoleSettings.TryGetValue(cacheKey, out var cached)) return cached; float value = EHRSourceBootstrap.ReadRoleSetting(role.ToString(), settingName); CachedRoleSettings[cacheKey] = value; return value; }", "direct_setting_field_query"));
        Dictionary<string, string> files = ApplyEdits(edits);
        return new(b.ToString(), files, new { schema = "ehr.explicit-source-bootstrap.v1", upstreamCommit = pin, compileProfile = profile,
            explicitSourceRoots = rooted.Count, rejectedOrUnneededSourceRoots = rejectedRoots, roleRpcDispatch = rpcRows,
            declaredRoleMethods = methodRows, settingFields = fieldRows, changedSourceFiles = files.Count, sourceEdits = edits.Distinct().ToArray(),
            deliberateScope = new[] {
                "SourceDeclaredTypes replaces bootstrap discovery, not arbitrary Assembly.GetTypes reflection equivalence. Compiler-generated state machines/closures are deliberately absent; native coroutine targets require actual metadata resolution.",
                "Ordinary object.GetType identity on explicitly rooted source classes is retained. No runtime Type.GetMethod/GetFields is used for generated role triggers, RPC dispatch or the three source setting queries.",
                "Unsupported ReceiveRPC forms and unknown type/name/setting lookups throw explicitly; no successful placeholder is returned.",
                "Optional map/Discord/desktop-console reflection is not a role bootstrap dependency and remains a separately reported platform integration boundary."
            }});

        void ReplaceInvocation(string path, string expression, string replacement)
        {
            SyntaxTree tree = compilation.SyntaxTrees.Single(t => t.FilePath == path);
            SyntaxNode[] candidates = tree.GetRoot().DescendantNodes().Where(n => n is InvocationExpressionSyntax || n is ConditionalAccessExpressionSyntax)
                .Where(n => Normalize(n.ToString()) == Normalize(expression)).ToArray();
            if (candidates.Length != 1) throw new InvalidOperationException("Expected exactly one bootstrap expression: " + expression + "; found " + candidates.Length);
            edits.Add(new(path, candidates[0].SpanStart, candidates[0].Span.End, replacement, "explicit_bootstrap_lookup"));
        }
    }

    static string Normalize(string value) => string.Concat(SyntaxFactory.ParseTokens(value).Select(t => t.Text));
    Dictionary<string, string> ApplyEdits(IEnumerable<SourceEdit> proposed)
    {
        var result = new Dictionary<string, string>();
        foreach (var group in proposed.Distinct().GroupBy(e => e.Path))
        {
            SourceEdit[] edits = group.OrderBy(e => e.Start).ToArray();
            if (edits.Zip(edits.Skip(1)).Any(pair => pair.First.End > pair.Second.Start)) throw new InvalidOperationException("Overlapping bootstrap edits in " + group.Key);
            string text = compilation.SyntaxTrees.Single(t => t.FilePath == group.Key).GetText().ToString();
            foreach (SourceEdit edit in edits.Reverse()) text = text[..edit.Start] + edit.Replacement + text[edit.End..];
            result[group.Key] = text;
        }
        return result;
    }
}

record SourceEdit(string Path, int Start, int End, string Replacement, string Reason);
record BootstrapOutput(string Code, Dictionary<string, string> Files, object Audit);
